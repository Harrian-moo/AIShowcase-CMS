def build_style_prompt(
    style: AdVisualStyle, prompt_brief: str | None = None
) -> StylePrompt:
    base, variants = STYLE_PROMPTS[style]
    variant_index = random.randrange(len(variants))
    prompt = base + variants[variant_index]
    brief = (prompt_brief or "").strip()
    if brief:
        prompt += f"补充创意要求：{brief[:200]}"
    return StylePrompt(prompt=prompt, variant_index=variant_index)

